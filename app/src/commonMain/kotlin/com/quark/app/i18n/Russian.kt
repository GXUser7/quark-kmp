/** One, few or many: 1 трек, 2 трека, 5 треков, 21 трек. */
internal fun plural(count: Number, one: String, few: String, many: String): String {
    val n = kotlin.math.abs(count.toLong())
    val lastTwo = n % 100
    val last = n % 10
    return when {
        lastTwo in 11..14 -> many
        last == 1L -> one
        last in 2..4 -> few
        else -> many
    }
}
