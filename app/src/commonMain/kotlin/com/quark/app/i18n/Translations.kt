/** Polish counts: 1 utwór, 2–4 utwory, 5 utworów, 22 utwory. */
internal fun polishPlural(count: Int, one: String, few: String, many: String): String {
    val lastTwo = count % 100
    val last = count % 10
    return when {
        count == 1 -> one
        last in 2..4 && lastTwo !in 12..14 -> few
        else -> many
    }
}
